/**
 * Builds the category icon sprite (DESIGN.md, Icons) from the Phosphor duotone files named in CATEGORY_ICON.
 * `bun run icons` writes src/web/icons/categories.svg and spriteUrl.ts; test/categoryIcons.test.ts fails if they drift.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import { CATEGORY_ICON } from "../src/catalog/category.js";

const PACKAGE = new URL("../node_modules/@phosphor-icons/core/", import.meta.url);
const OUT = new URL("../src/web/icons/", import.meta.url);

export function buildSprite(): { svg: string; url: string } {
  const version = (JSON.parse(fs.readFileSync(new URL("package.json", PACKAGE), "utf8")) as { version: string }).version;
  const license = fs.readFileSync(new URL("LICENSE", PACKAGE), "utf8").trim();
  const symbols = Object.entries(CATEGORY_ICON).map(([category, glyph]) => {
    const file = fs.readFileSync(new URL(`assets/duotone/${glyph}-duotone.svg`, PACKAGE), "utf8").trim();
    const inner = /^<svg[^>]*>([\s\S]*)<\/svg>$/.exec(file)?.[1];
    if (!inner) throw new Error(`unexpected markup in ${glyph}-duotone.svg`);
    return `<symbol id="${category}" viewBox="0 0 256 256" fill="currentColor">${inner}</symbol>`;
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
<!-- Phosphor Icons ${version}, duotone weight. Generated by scripts/build-category-sprite.ts: do not edit.

${license}
-->
${symbols.join("\n")}
</svg>
`;
  const hash = createHash("sha256").update(svg).digest("hex").slice(0, 10);
  return { svg, url: `/assets/icons/categories.${hash}.svg` };
}

export const spriteUrlModule = (url: string): string =>
  `// Generated by scripts/build-category-sprite.ts: do not edit.\nexport const CATEGORY_SPRITE_URL = ${JSON.stringify(url)};\n`;

if (import.meta.main) {
  const { svg, url } = buildSprite();
  fs.writeFileSync(new URL("categories.svg", OUT), svg);
  fs.writeFileSync(new URL("spriteUrl.ts", OUT), spriteUrlModule(url));
  console.log(`${url}: ${Buffer.byteLength(svg)} B`);
}
